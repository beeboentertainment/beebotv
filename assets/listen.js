/* Beebo "Listen" buttons.
   Each page loads this with <script src="assets/listen.js" data-page="PAGE" defer>.
   It reads audio/PAGE/manifest.json and adds a small Listen button + Transcript
   toggle to every element marked data-listen="SECTION-ID". Audio only loads when
   someone presses Listen. Generated by tools/make-site-narration.py. */
(function () {
  "use strict";
  var me = document.currentScript || document.querySelector('script[src*="listen.js"]');
  var page = (me && me.getAttribute("data-page")) ||
    (location.pathname.split("/").pop().replace(/\.html?$/, "") || "index");
  var base = "audio/" + page + "/";
  var player = null; // {audio, widget, clips, index}
  var uid = 0;

  function fmt(sec) {
    sec = Math.max(0, Math.round(sec));
    return Math.floor(sec / 60) + ":" + String(sec % 60).padStart(2, "0");
  }

  function el(tag, cls, text) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text != null) e.textContent = text;
    return e;
  }

  function placement(target) {
    // Never put a button inside a link, button or summary; go before that element instead.
    var wrapper = target.closest("a, button, summary, [role=tab]");
    if (wrapper && wrapper !== document.body) {
      return { node: wrapper, where: "beforebegin" };
    }
    var h = /^H[1-6]$/.test(target.tagName) ? target : target.querySelector("h1, h2, h3, h4");
    if (h && !h.closest("a, button, summary")) {
      // A heading that sits in a side-by-side row (flex/grid): put the button under the whole row.
      var row = h.parentElement;
      var cs = row && window.getComputedStyle ? window.getComputedStyle(row) : null;
      if (cs && /flex|grid/.test(cs.display) && !/column/.test(cs.flexDirection) &&
          row.children.length > 1 && row.tagName !== "MAIN" && row.tagName !== "BODY") {
        return { node: row, where: "afterend" };
      }
      return { node: h, where: "afterend" };
    }
    if (/^(LI|TR|TD|DT|DD)$/.test(target.tagName)) return { node: target, where: "afterbegin" };
    return { node: target, where: "beforebegin" };
  }

  function stop() {
    if (!player) return;
    player.audio.pause();
    setState(player.widget, "idle");
    player = null;
  }

  function setState(widget, state) {
    widget.setAttribute("data-state", state);
    var btn = widget.querySelector(".bb-listen-play");
    var label = btn.getAttribute("data-label");
    var icon = btn.querySelector(".bb-listen-icon");
    var word = btn.querySelector(".bb-listen-word");
    if (state === "playing") {
      icon.textContent = "❚❚";
      word.textContent = "Pause";
      btn.setAttribute("aria-label", "Pause: " + label);
      btn.setAttribute("aria-pressed", "true");
    } else {
      icon.textContent = "▶";
      word.textContent = state === "paused" ? "Resume" : "Listen";
      btn.setAttribute("aria-label", (state === "paused" ? "Resume: " : "Listen: ") + label);
      btn.setAttribute("aria-pressed", "false");
      if (state === "idle") {
        widget.querySelector(".bb-listen-bar i").style.width = "0";
        widget.querySelector(".bb-listen-time").textContent = fmt(widget._total);
      }
    }
  }

  function playClip(p) {
    var clip = p.clips[p.index];
    p.audio.src = base + clip.src;
    p.audio.play().catch(function () { setState(p.widget, "idle"); });
  }

  function toggle(widget, section) {
    if (player && player.widget === widget) {
      if (player.audio.paused) {
        player.audio.play();
        setState(widget, "playing");
      } else {
        player.audio.pause();
        setState(widget, "paused");
      }
      return;
    }
    stop();
    var audio = new Audio();
    audio.preload = "auto";
    var p = { audio: audio, widget: widget, clips: section.clips, index: 0 };
    player = p;
    var before = function () {
      var s = 0;
      for (var i = 0; i < p.index; i++) s += p.clips[i].duration;
      return s;
    };
    audio.addEventListener("timeupdate", function () {
      if (player !== p) return;
      var done = before() + audio.currentTime;
      widget.querySelector(".bb-listen-bar i").style.width = Math.min(100, (done / widget._total) * 100) + "%";
      widget.querySelector(".bb-listen-time").textContent = fmt(widget._total - done);
    });
    audio.addEventListener("ended", function () {
      if (player !== p) return;
      if (p.index + 1 < p.clips.length) {
        p.index++;
        playClip(p);
      } else {
        stop();
      }
    });
    audio.addEventListener("error", function () { if (player === p) stop(); });
    setState(widget, "playing");
    playClip(p);
  }

  function build(section, target) {
    var id = "bb-tx-" + (++uid);
    var total = section.duration || section.clips.reduce(function (s, c) { return s + c.duration; }, 0);
    var w = el("div", "bb-listen");
    w._total = total;
    w.setAttribute("data-state", "idle");

    var play = el("button", "bb-listen-play");
    play.type = "button";
    play.setAttribute("data-label", section.heading + " (" + fmt(total) + ")");
    play.appendChild(el("span", "bb-listen-icon", "▶")).setAttribute("aria-hidden", "true");
    play.appendChild(el("span", "bb-listen-word", "Listen"));
    var time = el("span", "bb-listen-time", fmt(total));
    time.setAttribute("aria-hidden", "true");
    play.appendChild(time);
    var bar = el("span", "bb-listen-bar");
    bar.setAttribute("aria-hidden", "true");
    bar.appendChild(el("i"));
    play.appendChild(bar);

    var tx = el("button", "bb-listen-tx", "Transcript");
    tx.type = "button";
    tx.setAttribute("aria-expanded", "false");
    tx.setAttribute("aria-controls", id);

    var panel = el("div", "bb-listen-transcript");
    panel.id = id;
    panel.hidden = true;
    section.clips.forEach(function (c) {
      c.text.forEach(function (t) { panel.appendChild(el("p", null, t)); });
    });

    play.addEventListener("click", function () { toggle(w, section); });
    tx.addEventListener("click", function () {
      var open = tx.getAttribute("aria-expanded") === "true";
      tx.setAttribute("aria-expanded", String(!open));
      tx.textContent = open ? "Transcript" : "Hide transcript";
      panel.hidden = open;
    });

    var row = el("div", "bb-listen-row");
    row.appendChild(play);
    row.appendChild(tx);
    w.appendChild(row);
    w.appendChild(panel);
    setState(w, "idle");

    var spot = placement(target);
    spot.node.insertAdjacentElement(spot.where, w);
    followVisibility(w, spot.node, target);
  }

  // A page can hide the card a Listen button belongs to (the Help page's search and category
  // filters set hidden on the card). The button must disappear with it, not float on its own.
  function followVisibility(w, anchor, target) {
    function gone(n) {
      if (!n) return false;
      if (n.closest && n.closest("[hidden]")) return true;
      try { return window.getComputedStyle(n).display === "none"; } catch (e) { return false; }
    }
    function sync() {
      var hide = gone(anchor) || gone(target);
      if (w.hidden !== hide) {
        w.hidden = hide;
        if (hide && player && player.widget === w) stop();
      }
    }
    sync();
    if (!window.MutationObserver) return;
    var mo = new MutationObserver(sync);
    [anchor, target].forEach(function (n) {
      for (; n && n !== document.documentElement; n = n.parentElement) {
        mo.observe(n, { attributes: true, attributeFilter: ["hidden", "style", "class"] });
      }
    });
  }

  function init(manifest) {
    var seen = {};
    (manifest.sections || []).forEach(function (section) {
      if (section.disabled || section.status === "stale" || !section.clips || !section.clips.length) return;
      var target = document.querySelector('[data-listen="' + section.id + '"]');
      if (!target) return;
      // Several link cards can share one grid: only one widget per spot.
      var spot = placement(target);
      var key = section.id;
      if (seen[key]) return;
      seen[key] = true;
      build(section, target);
    });
    document.addEventListener("keydown", function (e) {
      if (e.key === "Escape" && player) stop();
    });
  }

  function start() {
    if (!window.fetch) return;
    fetch(base + "manifest.json", { cache: "no-cache" })
      .then(function (r) { return r.ok ? r.json() : null; })
      .then(function (m) { if (m) init(m); })
      .catch(function () {});
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", start);
  else start();
})();
